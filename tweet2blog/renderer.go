// RenderHTML renders a thread as a standalone HTML file
func RenderHTML(thread *Thread, embedImages bool) (string, error) {
	css := getHTMLCSS()
	js := getHTMLJS()

	var sb strings.Builder

	// HTML Header
	sb.WriteString(`<!DOCTYPE html>
<html lang="en">
<head>
    <meta charset="UTF-8">
    <meta name="viewport" content="width=device-width, initial-scale=1.0">
    <title>`)
	sb.WriteString(html.EscapeString(thread.Title))
	sb.WriteString(`</title>
    <style>
`)
	sb.WriteString(css)
	sb.WriteString(`
    </style>
</head>
<body>
    <div class="container">
        <div class="header">
            <h1>`)
	sb.WriteString(html.EscapeString(thread.Title))
	sb.WriteString(`</h1>
            <div class="meta">
                <a href="https://x.com/`)
	sb.WriteString(thread.Author.Username)
	sb.WriteString(`" target="_blank" class="author">
                    @`)
	sb.WriteString(thread.Author.Username)
	sb.WriteString(`
                </a>
                <span class="tweet-count">`)
	sb.WriteString(fmt.Sprintf("%d tweets", len(thread.Tweets)))
	sb.WriteString(`</span>
            </div>
        </div>

        <div class="tweets">
`)

	// Render each tweet
	for _, tweet := range thread.Tweets {
		sb.WriteString(renderTweetHTML(tweet, embedImages))
	}

	sb.WriteString(`
        </div>

        <div class="footer">
            <p>Generated by tweet2blog • View on <a href="`)
	sb.WriteString(thread.URL)
	sb.WriteString(`" target="_blank">X/Twitter</a></p>
        </div>
    </div>

    <script>
`)
	sb.WriteString(js)
	sb.WriteString(`
    </script>
</body>
</html>
`)

	return sb.String(), nil
}

// renderTweetHTML renders a single tweet as HTML
func renderTweetHTML(tweet *Tweet, embedImages bool) string {
	var sb strings.Builder

	sb.WriteString(`            <div class="tweet">
                <div class="tweet-header">
                    <a href="https://x.com/`)
	sb.WriteString(tweet.Author.Username)
	sb.WriteString(`" target="_blank" class="user-link">
                        <strong>`)
	sb.WriteString(html.EscapeString(tweet.Author.Name))
	sb.WriteString(`</strong>
                        <span class="username">@`)
	sb.WriteString(tweet.Author.Username)
	sb.WriteString(`</span>
                    </a>
                    <span class="verified">`)
	if tweet.Author.Verified {
		sb.WriteString("✓")
	}
	sb.WriteString(`</span>
                </div>

                <div class="tweet-content">
                    <p>`)
	sb.WriteString(html.EscapeString(tweet.Text))
	sb.WriteString(`</p>
`)

	// Render media
	if len(tweet.Attachments.Media) > 0 {
		sb.WriteString(`                    <div class="media">
`)
		for _, media := range tweet.Attachments.Media {
			sb.WriteString(renderMediaHTML(media, embedImages))
		}
		sb.WriteString(`                    </div>
`)
	}

	// Render URLs
	if len(tweet.Attachments.URLs) > 0 {
		sb.WriteString(`                    <div class="urls">
`)
		for _, u := range tweet.Attachments.URLs {
			sb.WriteString(`                        <a href="`)
			sb.WriteString(html.EscapeString(u))
			sb.WriteString(`" target="_blank" rel="noopener">`)
			sb.WriteString(html.EscapeString(u))
			sb.WriteString(`</a><br>
`)
		}
		sb.WriteString(`                    </div>
`)
	}

	sb.WriteString(`                </div>

                <div class="tweet-footer">
                    <span class="date">`)
	sb.WriteString(tweet.CreatedAt.Format("Jan 2, 2006 • 3:04 PM"))
	sb.WriteString(`</span>
                    <div class="metrics">
                        <a href="https://x.com/`)
	sb.WriteString(tweet.Author.Username)
	sb.WriteString(`/status/`)
	sb.WriteString(tweet.ID)
	sb.WriteString(`" target="_blank">View on X</a>
                    </div>
                </div>
            </div>
`)

	return sb.String()
}

// renderMediaHTML renders media elements
func renderMediaHTML(media Media, embedImages bool) string {
	var sb strings.Builder

	switch media.Type {
	case "photo":
		sb.WriteString(`                        <div class="media-item">
                            <img src="`)
		if embedImages {
			// In real implementation, would fetch and encode as data URL
			sb.WriteString(media.URL)
		} else {
			sb.WriteString(html.EscapeString(media.URL))
		}
		sb.WriteString(`" alt="`)
		sb.WriteString(html.EscapeString(media.AltText))
		sb.WriteString(`" loading="lazy">
                        </div>
`)
	case "video", "animated_gif":
		sb.WriteString(`                        <div class="media-item">
                            <div class="video-placeholder">
                                <a href="`)
		sb.WriteString(html.EscapeString(media.URL))
		sb.WriteString(`" target="_blank">
                                    <img src="`)
		sb.WriteString(html.EscapeString(media.Preview))
		sb.WriteString(`" alt="Video thumbnail" loading="lazy">
                                    <div class="play-icon">▶</div>
                                </a>
                            </div>
                        </div>
`)
	}

	return sb.String()
}

