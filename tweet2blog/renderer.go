// getHTMLJS returns the embedded JavaScript
func getHTMLJS() string {
	return `
// Dark mode toggle
(function() {
    const prefersDark = window.matchMedia('(prefers-color-scheme: dark)').matches;
    
    if (prefersDark) {
        document.documentElement.style.colorScheme = 'dark';
    }

    // Lazy load images
    if ('IntersectionObserver' in window) {
        const images = document.querySelectorAll('img[loading="lazy"]');
        const imageObserver = new IntersectionObserver((entries, observer) => {
            entries.forEach(entry => {
                if (entry.isIntersecting) {
                    const img = entry.target;
                    img.src = img.src;
                    imageObserver.unobserve(img);
                }
            });
        });

        images.forEach(img => imageObserver.observe(img));
    }
})();
`
}

// RenderMarkdown renders a thread as markdown
func RenderMarkdown(thread *Thread) (string, error) {
	var sb strings.Builder

	sb.WriteString("# ")
	sb.WriteString(thread.Title)
	sb.WriteString("\n\n")

	sb.WriteString("**@")
	sb.WriteString(thread.Author.Username)
	sb.WriteString("** • ")
	sb.WriteString(fmt.Sprintf("%d tweets\n\n", len(thread.Tweets)))
	sb.WriteString("---\n\n")

	for i, tweet := range thread.Tweets {
		sb.WriteString(fmt.Sprintf("## Tweet %d\n\n", i+1))
		sb.WriteString(tweet.Text)
		sb.WriteString("\n\n")

		sb.WriteString("**By:** [@")
		sb.WriteString(tweet.Author.Username)
		sb.WriteString("](https://x.com/")
		sb.WriteString(tweet.Author.Username)
		sb.WriteString(")\n\n")

		sb.WriteString("**Date:** ")
		sb.WriteString(tweet.CreatedAt.Format("January 2, 2006 at 3:04 PM"))
		sb.WriteString("\n\n")

		if len(tweet.Attachments.Media) > 0 {
			sb.WriteString("**Media:**\n")
			for _, media := range tweet.Attachments.Media {
				sb.WriteString("- [")
				sb.WriteString(strings.ToTitle(media.Type))
				sb.WriteString("](")
				sb.WriteString(media.URL)
				sb.WriteString(")\n")
			}
			sb.WriteString("\n")
		}

		if len(tweet.Attachments.URLs) > 0 {
			sb.WriteString("**Links:**\n")
			for _, u := range tweet.Attachments.URLs {
				sb.WriteString("- ")
				sb.WriteString(u)
				sb.WriteString("\n")
			}
			sb.WriteString("\n")
		}

		sb.WriteString("---\n\n")
	}

	sb.WriteString("[View on X/Twitter](")
	sb.WriteString(thread.URL)
	sb.WriteString(")\n")

	return sb.String(), nil
}

// RenderJSON renders a thread as JSON
func RenderJSON(thread *Thread) (string, error) {
	data, err := json.MarshalIndent(thread, "", "  ")
	if err != nil {
		return "", err
	}
	return string(data), nil
}

// EmbedImageAsDataURL converts an image URL to a data URL
func EmbedImageAsDataURL(imageURL string) (string, error) {
	resp, err := http.Get(imageURL)
	if err != nil {
		return "", err
	}
	defer resp.Body.Close()

	body, err := io.ReadAll(resp.Body)
	if err != nil {
		return "", err
	}

	contentType := resp.Header.Get("Content-Type")
	if contentType == "" {
		contentType = "image/jpeg"
	}

	dataURL := fmt.Sprintf("data:%s;base64,%s", contentType, encodeBase64(body))
	return dataURL, nil
}

// encodeBase64 encodes bytes as base64
func encodeBase64(data []byte) string {
	const base64chars = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/"
	var result strings.Builder

	for i := 0; i < len(data); i += 3 {
		b1 := data[i]
		var b2, b3 byte
		if i+1 < len(data) {
			b2 = data[i+1]
		}
		if i+2 < len(data) {
			b3 = data[i+2]
		}

		result.WriteByte(base64chars[b1>>2])
		result.WriteByte(base64chars[((b1&0x03)<<4)|((b2&0xf0)>>4)])

		if i+1 < len(data) {
			result.WriteByte(base64chars[((b2&0x0f)<<2)|((b3&0xc0)>>6)])
		} else {
			result.WriteByte('=')
		}

		if i+2 < len(data) {
			result.WriteByte(base64chars[b3&0x3f])
		} else {
			result.WriteByte('=')
		}
	}

	return result.String()
}
